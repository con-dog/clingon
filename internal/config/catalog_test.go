package config

import (
	"fmt"
	"go/format"
	"os"
	"reflect"
	"strings"
	"testing"
)

// catalog.go is every built-in pack's details, so a run needn't parse
// them all. This test works them out from the packs and fails if the file
// is behind.
//
// After changing a pack: UPDATE_CATALOG=1 go test ./internal/config/
const catalogFile = "catalog.go"

func TestCatalogIsCurrent(t *testing.T) {
	want, err := readPacks()
	if err != nil {
		t.Fatal(err)
	}
	if reflect.DeepEqual(want, catalog) {
		return
	}
	if os.Getenv("UPDATE_CATALOG") == "" {
		t.Fatalf("%s is out of date with the packs: run UPDATE_CATALOG=1 go test ./internal/config/", catalogFile)
	}
	if err := os.WriteFile(catalogFile, catalogSource(want), 0o644); err != nil {
		t.Fatal(err)
	}
}

// readPacks works out the catalog from the packs themselves.
func readPacks() ([]Pack, error) {
	var out []Pack
	for _, name := range builtinPackNames() {
		p := Pack{Name: name}
		var info packInfo
		var groups []Group
		for _, f := range builtinFiles(name) {
			data, err := builtinFile(name, f)
			if err != nil {
				return nil, err
			}
			part, err := parsePackFile(f, data)
			if err != nil {
				return nil, err
			}
			if part.info != nil {
				info = *part.info
				continue
			}
			groups = append(groups, *part.group)
			p.Modules = append(p.Modules, Module{moduleSlug(f), part.group.Name, part.group.Description, len(part.group.Commands)})
			p.Commands += len(part.group.Commands)
		}
		p.Description, p.Requires, p.Default = info.Description, info.Requires, defaultPacks[name]
		p.Sections = []string{info.Name}
		// Only for a pack with no tools of its own (package-managers: brew):
		// in one that has them, a group's tool is optional.
		for _, g := range groups {
			if len(info.Requires) == 0 && len(g.Requires) > 0 {
				p.AnyOf = append(p.AnyOf, g.Requires[0])
			}
		}
		out = append(out, p)
	}
	return out, nil
}

func catalogSource(ps []Pack) []byte {
	list := func(l []string) string {
		if l == nil {
			return "nil"
		}
		q := make([]string, len(l))
		for i, s := range l {
			q[i] = fmt.Sprintf("%q", s)
		}
		return "[]string{" + strings.Join(q, ", ") + "}"
	}
	var b strings.Builder
	b.WriteString("// Code generated by TestCatalogIsCurrent (UPDATE_CATALOG=1 go test ./internal/config/); DO NOT EDIT.\n\npackage config\n\n")
	b.WriteString("// catalog is every built-in pack, as Packs gives them.\nvar catalog = []Pack{\n")
	for _, p := range ps {
		mods := make([]string, len(p.Modules))
		for i, m := range p.Modules {
			mods[i] = fmt.Sprintf("{%q, %q, %q, %d}", m.Slug, m.Name, m.Description, m.Commands)
		}
		fmt.Fprintf(&b, "\t{Name: %q, Description: %q, Requires: %s, AnyOf: %s, Default: %t, Sections: %s, Commands: %d, Modules: []Module{%s}},\n",
			p.Name, p.Description, list(p.Requires), list(p.AnyOf), p.Default, list(p.Sections), p.Commands, strings.Join(mods, ", "))
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	return src
}

// parse reads a whole Config from YAML with its sections spelled out, which is
// the handiest way to write one down in a test.
func parse(name string, data []byte) (*Config, error) {
	var c Config
	if err := decodeStrict(name, data, &c); err != nil {
		return nil, err
	}
	return &c, nil
}
