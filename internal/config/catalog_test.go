package config

import (
	"fmt"
	"go/format"
	"os"
	"reflect"
	"strings"
	"testing"
)

// catalog.go is every built-in pack's details, so a run needn't parse
// them all. This test works them out from the packs and fails if the file
// is behind.
//
// After changing a pack: UPDATE_CATALOG=1 go test ./internal/config/
const catalogFile = "catalog.go"

func TestCatalogIsCurrent(t *testing.T) {
	want, err := readPacks()
	if err != nil {
		t.Fatal(err)
	}
	if reflect.DeepEqual(want, catalog) {
		return
	}
	if os.Getenv("UPDATE_CATALOG") == "" {
		t.Fatalf("%s is out of date with the packs: run UPDATE_CATALOG=1 go test ./internal/config/", catalogFile)
	}
	if err := os.WriteFile(catalogFile, catalogSource(want), 0o644); err != nil {
		t.Fatal(err)
	}
}

// readPacks works out the catalog from the packs themselves.
func readPacks() ([]Pack, error) {
	entries, err := packFS.ReadDir("packs")
	if err != nil {
		return nil, err
	}
	var out []Pack
	for _, e := range entries {
		name := strings.TrimSuffix(e.Name(), ".yaml")
		c, err := loadPack(name)
		if err != nil {
			return nil, err
		}
		p := Pack{Name: name, Version: c.Version, Description: c.Description, Requires: c.Requires, Default: c.Default}
		for i := range c.Sections {
			p.Sections = append(p.Sections, c.Sections[i].Name)
			p.Commands += len(c.Sections[i].All())
			// Only for a pack with no tools of its own (package-managers:
			// brew): in one that has them, a group's tool is optional.
			for _, g := range c.Sections[i].Groups {
				if len(c.Requires) == 0 && len(g.Requires) > 0 {
					p.AnyOf = append(p.AnyOf, g.Requires[0])
				}
			}
		}
		out = append(out, p)
	}
	return out, nil
}

func catalogSource(ps []Pack) []byte {
	list := func(l []string) string {
		if l == nil {
			return "nil"
		}
		q := make([]string, len(l))
		for i, s := range l {
			q[i] = fmt.Sprintf("%q", s)
		}
		return "[]string{" + strings.Join(q, ", ") + "}"
	}
	var b strings.Builder
	b.WriteString("// Code generated by TestCatalogIsCurrent (UPDATE_CATALOG=1 go test ./internal/config/); DO NOT EDIT.\n\npackage config\n\n")
	b.WriteString("// catalog is every built-in pack, as Packs gives them.\nvar catalog = []Pack{\n")
	for _, p := range ps {
		fmt.Fprintf(&b, "\t{Name: %q, Version: %q, Description: %q, Requires: %s, AnyOf: %s, Default: %t, Sections: %s, Commands: %d},\n",
			p.Name, p.Version, p.Description, list(p.Requires), list(p.AnyOf), p.Default, list(p.Sections), p.Commands)
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	return src
}
